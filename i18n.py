LANGS = {"en": EN, "ru": RU, "zh": ZH}


def detect_lang(uid):
    """Язык юзера из config.json (langs), дефолт en."""
    try:
        cfg = json.loads(_cfg_path.read_text())
        return cfg.get("langs", {}).get(str(uid), "en")
    except Exception:
        return "en"


def set_lang(uid, lang):
    lang = lang if lang in LANGS else "en"
    cfg = json.loads(_cfg_path.read_text())
    cfg.setdefault("langs", {})[str(uid)] = lang
    _cfg_path.write_text(json.dumps(cfg, ensure_ascii=False, indent=2))


def S(uid=None, lang=None):
    """Строки для юзера: S(76102...).BTN_STATUS. Без uid — дефолт en."""
    return LANGS[lang or detect_lang(uid)]


